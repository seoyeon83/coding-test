import sys
from collections import deque


# 동남서북 
dr = [0, 1, 0, -1]
dc = [1, 0, -1, 0] 

def bfs(r, c):
    # 현재 바다 상황 복제, 0은 0으로, 산호초와 거북이는 -1로
    grid = [[0] * N for _ in range(N)]
    grid[r][c] = 1
    for x in range(N):
        for y in range(N):
            if ocean[x][y] != 0:
                grid[x][y] = -1
                
    q = deque([(r, c)])                 # 큐

    while q:
        r, c = q.popleft()
        for d in range(4):
            nr, nc = r + dr[d], c + dc[d]

            if not (0 <= nr < N and 0 <= nc < N):
                continue
            if grid[nr][nc] != 0:
                continue

            q.append((nr, nc))
            grid[nr][nc] = grid[r][c] + 1
            
    return grid[N-1][N-1]
    

N, M, K = map(int, sys.stdin.readline().split())

# 바다 정보 (0: 빈 공간, 1: 산호초 -> -1로 바꿔 표기)
ocean = []
for _ in range(N):
    row = list(map(int, sys.stdin.readline().split()))
    for i in range(N):
        if row[i] == 1:
            row[i] = -1
    ocean.append(row)
 
# 바다 거북의 초기 위치 (id 순, r, c)
positions = {}  # 거북이 위치는 dict로 계속 추적
for id in range(1, M+1):
    r, c = map(int, sys.stdin.readline().split())
    ocean[r][c] = id
    positions[id] = [r, c]

# 화산 위치, 분출 임계치 (r, c, P, h(압력))
mountains = []
for _ in range(K):
    row = list(map(int, sys.stdin.readline().split()))
    row.append(0)       # 압력
    mountains.append(row)

status = [-1] * (M + 1)  # 거북이 상태 기록, id는 1부터 시작하므로
# 각 턴 진행 (최대 100턴)
for turn in range(1, 101):
    # 만약 바다거북이 다 목적지에 도착하거나 화석이 됐다면 중단
    if not positions:
        break

    # 1단계: 바다거북 이동 (목적지 도착 시 status 기록)
    for id in sorted(positions.keys()):  # id 순서대로 이동
        cr, cc = positions[id]  # 현재 거북이 위치

        # 방향 별로 도달 가능한지, 최단거리 방향은 어디인지 탐색
        direct = -1
        min_route = N * N
        for d in range(4):
            # 방향별 다음 칸, 범위 안인지 장애물이 있는지
            nr, nc = cr + dr[d], cc + dc[d]
            if not (0 <= nr < N and 0 <= nc < N):
                continue
            if ocean[nr][nc] != 0:
                continue
            
            result = bfs(nr, nc)
            # 최단경로 갱신
            if result > 0 and result < min_route:
                min_route = result
                direct = d

        # 최단경로가 존재한다면 이동, 존재하지 않으면 이동 X
        if direct >= 0:
            # 최단경로 방향으로 이동
            nr, nc = cr + dr[direct], cc + dc[direct]
            ocean[cr][cc] = 0

            if nr == N-1 and nc == N-1: # 만약 탈출한 경우
                del positions[id]       # 위치 추적 중단
                status[id] = turn       # status에 상태 기록

            else:
                ocean[nr][nc] = id
                positions[id] = [nr, nc]

    # 2단계: 화산 압력(10) 증가
    fire = deque()
    done = set()
    for k in range(K):
        mountains[k][3] += 10
        if mountains[k][3] >= mountains[k][2]:  # 임계값을 넘으면 큐에 추가
            fire.append(k)
            done.add(k)         # 화산 분출된 산에 기록

    # 3단계: 화산 분출 및 연쇄 반응
    heat = [[0] * N for _ in range(N)]
    while fire:
        k = fire.popleft()
        cr, cc, P, _ = mountains[k] # 현재 위치, P, h

        # 열기 전파 (상하좌우, 한 칸 이동할 때마다 이전 칸 열기//2, 산호초 만나면 중단)
        heat[cr][cc] = P
        for d in range(4):
            r, c = cr, cc               # r, c는 이 안에서만 도는 변수로 분리 (cr, cc 지키기)
            while True:
                nr, nc = r + dr[d], c + dc[d]
                if not(0 <= nr < N and 0 <= nc < N):
                    break
                if ocean[nr][nc] == -1:     # 산호초
                    break
                next_heat = heat[r][c] // 2
                if next_heat <= 0: 
                    break
                heat[nr][nc] += next_heat
                r, c = nr, nc
        
        # 추가 분출되는 산 있는지 검사 -> 있으면 큐에 추가
        for i in range(K):
            if i in done:
                continue
            if mountains[i][3] + heat[mountains[i][0]][mountains[i][1]] < mountains[i][2]:
                continue

            fire.append(i)
            done.add(i)    
        
    # 거북이 상태 확인
    for id in sorted(positions.keys()):
        cr, cc = positions[id]
        if heat[cr][cc] >= 20:  # 화석화
            del positions[id]   # 추적 중단

    # 4단계: 환경 초기화
    # 분출을 일으킨 화산의 압력을 0으로 초기화
    for k in done:
        mountains[k][3] = 0

# 결과 출력
for i in range(1, M + 1):
    print(status[i])


