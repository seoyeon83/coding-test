import sys
from collections import deque


def bfs(f, r, c, visited):
    q = deque([(r, c)])
    result = [(grid[r][c][1], r, c)]
    visited[r][c] = True

    while q:
        r, c = q.popleft()
        for i in range(4):
            nr, nc = r + dr[i], c + dc[i]
            if not (0 <= nr < N and 0 <= nc < N):
                continue
            if visited[nr][nc]:
                continue
            if grid[nr][nc][0] != f:
                continue 
            
            q.append((nr, nc))
            result.append((grid[nr][nc][1], nr, nc))
            visited[nr][nc] = True

    return result

N, T = map(int, sys.stdin.readline().split())

grid = []
for _ in range(N):
    fs = list(sys.stdin.readline().rstrip())
    row = []
    for f in fs:
        row.append([f, 0])
    grid.append(row)

for i in range(N):
    bs = list(map(int, sys.stdin.readline().split()))
    for j, v in enumerate(bs):
        grid[i][j][1] = v

# 북남서동
dr = [-1, 1, 0, 0]
dc = [0, 0, -1, 1]

for day in range(T):
    # 1. 아침
    for r in range(N):
        for c in range(N):
            grid[r][c][1] += 1
    
    # 2. 점심: 그룹 형성
    leaders = []
    visited = [[False] * N for _ in range(N)]
    # 그룹 탐색해서 각 그룹원 좌표 수집
    for r in range(N):
        for c in range(N):
            if not visited[r][c]:
                members = bfs(grid[r][c][0], r, c, visited)

                # 대표자 선출 (신앙심, r, c)
                members.sort(key=lambda x: (-x[0], x[1], x[2]))
                leader = members[0]
                
                # 신앙심 차감 및 추가
                for _, cr, cc in members[1:]:
                    grid[cr][cc][1] -= 1

                grid[leader[1]][leader[2]][1] += (len(members)-1)
                # 음식, 신앙심, r, c
                leaders.append(
                    (grid[leader[1]][leader[2]][0], grid[leader[1]][leader[2]][1], 
                    leader[1], leader[2]))

    # 3. 저녁
    # 대표자 음식(개수), -신앙심, r, c 기준으로 정렬 -> 전파 순서 설정
    leaders.sort(key=lambda x: (len(x[0]), -x[1], x[2], x[3]))
    # 이미 전파를 당한 대표자는 따로 기록
    already = set()

    # 대표자별로 전파 진행
    for f, b, r, c in leaders:
        if (r, c) in already:                   # 방어모드인 대표자 -> 전파 불가
            continue

        x = b-1             # 간절함
        d = b%4             # 방향
        grid[r][c][1] = 1   # 남은 신앙심

        while x > 0:
            nr, nc = r + dr[d], c + dc[d]
            if not (0 <= nr < N and 0 <= nc < N):   # 격자를 넘어갈 경우
                break
            if grid[nr][nc][0] == f:                # 신봉 음식이 같은 경우    
                r, c = nr, nc
                continue
            
            # 대표자가 전파를 받는 경우 -> 방어모드 -> 대표자 제외하게 기록
            for leader in leaders:
                if leader[2] == nr and leader[3] == nc:
                    already.add((nr, nc))
                    break

            # 전파 진행
            # 신앙심, 간절함 비교
            if x > grid[nr][nc][1]:     # 강한 전파
                grid[nr][nc][0] = f            # 사상 동화
                x -= (grid[nr][nc][1] + 1)      # 간절함 차감
                grid[nr][nc][1] += 1            # 신앙심 증가

            else:                   # 약한 전파
                # 신봉 음식 합치기
                # 이때 완전히 같지 않고 TC, TM같을 수 있으므로 set()을 활용해 합치자
                grid[nr][nc][0] = ''.join(sorted((set(grid[nr][nc][0]) | set(f))))
                grid[nr][nc][1] += x
                x = 0
            
            r, c = nr, nc

    # 저녁 후 신봉자들의 신앙심 총합 계산 및 출력
    foods = ['CMT', 'CT', 'MT', 'CM', 'M', 'C', 'T']
    # T, C, M, CT, CM, MT, CMT
    summary = {food : 0 for food in foods}
    for r in range(N):
        for c in range(N):
            summary[grid[r][c][0]] += grid[r][c][1]

    for food in foods:
        print(summary[food], end=' ')
    print()


